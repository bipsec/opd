"""Thin wrapper: reports/quant_validation.{md,json} from models/quant/_val/*/*.json (PLAN 4.2)."""

from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
ORDER = ("fp8_w8a8", "awq_w4a16_g128", "nvfp4", "gptq_w3a16_g128")
LABEL = {
    "fp8_w8a8": "FP8 W8A8 (static)",
    "awq_w4a16_g128": "AWQ W4A16 g128",
    "nvfp4": "NVFP4",
    "gptq_w3a16_g128": "GPTQ W3A16 g128",
}
INTRO = (
    "llm-compressor 0.15.0 installed with `--no-deps` (its torch<=2.14.1 pin bypassed; "
    "torch 2.15.0a0 from NGC) in `qopd-quant`; each S2 checkpoint loaded and scored by the "
    "unchanged vLLM 0.31 in `qopd-dev` on the same 20 exact-id S2 rollouts "
    "(`runs/agreement/S2_vllm_vs_hf_s0`, top-20) and compared with BF16 S2. Generated by "
    "`scripts/quant_validation_report.py`."
)
HEADER = (
    "| Checkpoint | tool | build s | tokens | mean abs Δ (nats) | median | p99 | max "
    "| top-1 agr. | top-20 overlap |"
)


def collect() -> list[dict]:
    rows = []
    for fmt in ORDER:
        d = ROOT / "models" / "quant" / "_val" / f"S2-{fmt}"
        if not ((d / "validation.json").exists() and (d / "recipe.json").exists()):
            continue
        r = json.loads((d / "recipe.json").read_text())
        v = json.loads((d / "validation.json").read_text())
        rows.append(
            {
                "format": fmt,
                "label": LABEL[fmt],
                "tool": r["tool"],
                "tool_version": r["tool_version"],
                "build_s": r["seconds"],
                "calibration_sha256": r["calibration_sha256"],
                **v,
            }
        )
    return rows


def main() -> None:
    rows = collect()
    (ROOT / "reports" / "quant_validation.json").write_text(json.dumps(rows, indent=2))
    lines = [
        "# Quantization tooling validation on S2 (step 4.2)",
        "",
        INTRO,
        "",
        HEADER,
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: |",
    ]
    for x in rows:
        cells = [
            x["label"],
            f"{x['tool']} {x['tool_version']}",
            f"{x['build_s']:.0f}",
            f"{x['n_tokens']:.0f}",
            f"{x['mean_abs_diff']:.3f}",
            f"{x['median_abs_diff']:.4f}",
            f"{x['p99_abs_diff']:.3f}",
            f"{x['max_abs_diff']:.2f}",
            f"{x['top1_agreement']:.3f}",
            f"{x['topk_overlap']:.3f}",
        ]
        lines.append("| " + " | ".join(cells) + " |")
    if rows:
        sha = rows[0]["calibration_sha256"][:16]
        lines += ["", f"Calibration: `data/calibration/t16_traces.jsonl` (sha256 {sha}).", ""]
    (ROOT / "reports" / "quant_validation.md").write_text("\n".join(lines))
    print(f"wrote reports/quant_validation.md ({len(rows)} rows)")


if __name__ == "__main__":
    main()
