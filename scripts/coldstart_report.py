"""Thin wrapper: reports/coldstart.{md,json} — before/after of the cold-start students (PLAN 5.3).

Before = the official student (n=1 sanity runs); after = the cold-start checkpoint. Paired
per-problem differences (after mean over samples − before) with a normal 95% interval.
Stdlib only; reads runs/eval/*/samples.jsonl and summary.json.
"""

from __future__ import annotations

import json
import math
import statistics
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
EVAL = ROOT / "runs" / "eval"
RUNS = {  # student -> suite -> (before run, after run)
    st: {
        "math500": (f"{st}__gsm8k+math500__n1__t16384__s0", f"{st}-cs__math500__n4__t16384__s0"),
        "gsm8k": (f"{st}__gsm8k+math500__n1__t16384__s0", f"{st}-cs__gsm8k__n1__t16384__s0"),
    }
    for st in ("S2", "S1")
}


def samples(run: str, suite: str) -> dict[str, list[dict]]:
    out: dict[str, list[dict]] = defaultdict(list)
    for line in (EVAL / run / "samples.jsonl").open():
        r = json.loads(line)
        if r["suite"] == suite:
            out[r["problem_id"]].append(r)
    return out


def side(per: dict[str, list[dict]]) -> dict[str, float]:
    rs = [r for v in per.values() for r in v]
    fin = [r for r in rs if r["finish_reason"] != "length"]
    return {
        "n_problems": len(per),
        "samples_per_problem": len(rs) / len(per),
        "pass_at_1": statistics.fmean(
            statistics.fmean(r["correct"] for r in v) for v in per.values()
        ),
        "truncation_rate": sum(r["finish_reason"] == "length" for r in rs) / len(rs),
        "acc_finished": sum(r["correct"] for r in fin) / len(fin) if fin else float("nan"),
        "mean_tokens": statistics.fmean(r["n_tokens"] for r in rs),
    }


def compare(before_run: str, after_run: str, suite: str) -> dict | None:
    if not all((EVAL / r / "DONE").exists() for r in (before_run, after_run)):
        return None
    b, a = samples(before_run, suite), samples(after_run, suite)
    ids = sorted(set(a) & set(b))
    d = [
        statistics.fmean(r["correct"] for r in a[i]) - statistics.fmean(r["correct"] for r in b[i])
        for i in ids
    ]
    se = statistics.stdev(d) / math.sqrt(len(d))
    m = statistics.fmean(d)
    return {
        "before_run": before_run,
        "after_run": after_run,
        "before": side(b),
        "after": side(a),
        "diff": m,
        "diff_ci95": [m - 1.96 * se, m + 1.96 * se],
        "n_paired": len(ids),
    }


def main() -> None:
    res = {
        st: {s: c for s, (br, ar) in suites.items() if (c := compare(br, ar, s))}
        for st, suites in RUNS.items()
    }
    res = {k: v for k, v in res.items() if v}
    (ROOT / "reports" / "coldstart.json").write_text(json.dumps(res, indent=2))
    stats = json.loads((ROOT / "data" / "coldstart" / "coldstart_stats.json").read_text())
    pc = lambda x: f"{100 * x:.1f}"  # noqa: E731
    lines = [
        "# Cold-start students (step 5.3)",
        "",
        f"SFT: 1 epoch on {stats['n_kept']:,} verified T16 traces (`data/coldstart/traces.jsonl`, "
        f"sha256 {stats['sha256'][:12]}…), lr 1e-5, BF16 mixed precision. Before = official "
        "student (n=1 sanity run); after = cold-start checkpoint. Thinking mode, T 0.6, top-p "
        "0.95, 16,384 tokens. Δ = paired per-problem difference in points, normal 95% CI. "
        "Generated by `scripts/coldstart_report.py`.",
        "",
        "| Student | Suite | samples (before/after) | pass@1 before | pass@1 after | Δ (95% CI) "
        "| trunc. before | trunc. after | acc. finished before/after | mean tokens before/after |",
        "| --- | --- | --- | ---: | ---: | --- | ---: | ---: | --- | --- |",
    ]
    for st, suites in res.items():
        for s, c in suites.items():
            b, a = c["before"], c["after"]
            lo, hi = c["diff_ci95"]
            lines.append(
                f"| {st} | {s} | {b['samples_per_problem']:.0f}/{a['samples_per_problem']:.0f} "
                f"| {pc(b['pass_at_1'])} | {pc(a['pass_at_1'])} "
                f"| {100 * c['diff']:+.1f} ({100 * lo:+.1f}, {100 * hi:+.1f}) "
                f"| {pc(b['truncation_rate'])} | {pc(a['truncation_rate'])} "
                f"| {pc(b['acc_finished'])} / {pc(a['acc_finished'])} "
                f"| {b['mean_tokens']:,.0f} / {a['mean_tokens']:,.0f} |"
            )
    (ROOT / "reports" / "coldstart.md").write_text("\n".join(lines) + "\n")
    print(f"wrote reports/coldstart.md ({sum(len(v) for v in res.values())} rows)", file=sys.stderr)


if __name__ == "__main__":
    main()
