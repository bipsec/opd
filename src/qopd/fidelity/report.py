"""E1 report (PLAN 7.4): fidelity JSONs per rung, reports/e1.md and Figure 1, from saved files.

Layout (CLAUDE.md run contract under ``runs/e1/``)::

    runs/e1/<student>/pool/rollouts.jsonl, student.npz, scores/<rung>/   (7.1, 7.2)
    runs/e1/<student>/fidelity/<rung>.json                               (this module)

Every number in ``reports/e1.md`` is read from those JSON files (CLAUDE.md rule 6).
"""

from __future__ import annotations

from pathlib import Path
from typing import Any

from qopd.config import PROJECT_ROOT, project_relative
from qopd.fidelity.metrics import FidelityReport
from qopd.fidelity.pool import fidelity_for
from qopd.utils import io

E1_ROOT = PROJECT_ROOT / "runs" / "e1"
E1_REPORT = PROJECT_ROOT / "reports" / "e1.md"
REFERENCE = "T16"
COLUMNS = (
    ("pearson", "Pearson r", "{:.3f}"),
    ("mae", "MAE", "{:.4f}"),
    ("topk_kl", "top-20 KL", "{:.4f}"),
    ("topk_kl_imputed", "KL imputed", "{:.1%}"),
    ("top1_agreement", "top-1 agr.", "{:.3f}"),
    ("sign_flip_rate", "sign flips", "{:.3%}"),
)


def scored_rungs(pool_dir: Path) -> list[str]:
    """Rungs whose scoring finished (DONE marker), reference excluded."""
    d = pool_dir / "scores"
    return (
        sorted(p.name for p in d.iterdir() if (p / "DONE").exists() and p.name != REFERENCE)
        if d.exists()
        else []
    )


def compute_all(root: Path = E1_ROOT) -> dict[str, dict[str, dict[str, Any]]]:
    """Write ``<student>/fidelity/<rung>.json`` for every scored rung; returns them all."""
    out: dict[str, dict[str, dict[str, Any]]] = {}
    for student_dir in (
        sorted(p for p in root.iterdir() if (p / "pool").is_dir()) if root.exists() else []
    ):
        pool = student_dir / "pool"
        if not (pool / "scores" / REFERENCE / "DONE").exists():
            continue
        for rung in scored_rungs(pool):
            rep: FidelityReport = fidelity_for(pool, rung, REFERENCE, student_dir.name)
            data = rep.to_dict()
            io.write_json(student_dir / "fidelity" / f"{rung}.json", data)
            out.setdefault(student_dir.name, {})[rung] = data
    return out


def load_all(root: Path = E1_ROOT) -> dict[str, dict[str, dict[str, Any]]]:
    out: dict[str, dict[str, dict[str, Any]]] = {}
    for f in sorted(root.glob("*/fidelity/*.json")) if root.exists() else []:
        out.setdefault(f.parent.parent.name, {})[f.stem] = io.read_json(f)
    return out


def _fmt(v: Any, fmt: str) -> str:
    return "TBD" if v is None else fmt.format(v)


def write_report(
    results: dict[str, dict[str, dict[str, Any]]],
    figure: Path | None,
    report: Path = E1_REPORT,
    root: Path = E1_ROOT,
) -> Path:
    from qopd.paper.figures import RUNG_ORDER  # noqa: PLC0415

    lines = [
        "# E1 — teacher-signal fidelity (step 7.4)",
        "",
        f"Every rung against {REFERENCE} on the same fixed rollout pool per student. "
        "Generated by `qopd report e1` from `runs/e1/<student>/fidelity/<rung>.json`; "
        "do not edit by hand.",
        "",
    ]
    if not results:
        lines += ["TBD: no scored pools yet (steps 7.1/7.2).", ""]
    for student, rungs in sorted(results.items()):
        lines += [
            f"## Student {student}",
            "",
            "| Rung | tokens | " + " | ".join(c[1] for c in COLUMNS) + " | informativeness |",
            "| --- | ---: | " + " | ".join("---:" for _ in COLUMNS) + " | ---: |",
        ]
        for rung in [r for r in RUNG_ORDER if r in rungs]:
            d = rungs[rung]
            cells = [_fmt(d.get(k), f) for k, _, f in COLUMNS]
            inf = (
                "TBD (definition pending)"
                if d.get("informativeness") is None
                else f"{d['informativeness']:.3f}"
            )
            lines.append(f"| {rung} | {d['n_tokens']:,} | " + " | ".join(cells) + f" | {inf} |")
        lines.append("")
    if figure is not None:
        lines += [f"![Figure 1]({Path('..') / project_relative(figure)})", ""]
    lines += [f"Sources: `{project_relative(root)}/<student>/fidelity/*.json`.", ""]
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines))
    return report


def run_e1_report(root: Path = E1_ROOT, report: Path = E1_REPORT) -> tuple[Path, int]:
    """Compute fidelity for every scored rung, render Figure 1 and reports/e1.md."""
    from qopd.paper.figures import FIG_DIR, fig_fidelity  # noqa: PLC0415

    compute_all(root)
    results = load_all(root)
    fig = fig_fidelity(results, FIG_DIR / "fidelity.pdf") if results else None
    n = sum(len(v) for v in results.values())
    return write_report(results, fig, report, root), n
