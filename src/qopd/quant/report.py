"""Rung table (PLAN 4.1-4.4): reports/rungs.md and reports/results/rungs.json, from files only.

Per teacher rung: format, backend, tool + version (``models/quant/<rung>/recipe.json``, Phase 4.2),
weight size on disk (sum of ``*.safetensors`` / ``*.gguf``), load time, memory added at load and
scoring throughput (``runs/teacher_bench/<rung>_n200/summary.json``, 4.1/4.3), and MATH-500
pass@1 (``runs/eval/<rung>__math500__n1__*/summary.json``, 4.4). Missing values are TBD.
"""

from __future__ import annotations

import os
from pathlib import Path
from typing import Any

from qopd.config import CONFIG_ROOT, PROJECT_ROOT, ModelCfg, QuantCfg, load
from qopd.utils import io

RUNGS = ("T16", "T8", "T4-fp", "T4-int", "T3", "T2", "D16", "D8", "D4")
RESULTS = PROJECT_ROOT / "reports" / "results" / "rungs.json"
REPORT = PROJECT_ROOT / "reports" / "rungs.md"


def weights_dir(cfg: ModelCfg) -> Path | None:
    """Local directory holding the rung's weights (HF cache snapshot or models/quant/<rung>)."""
    if cfg.source_type == "local":
        p = Path(cfg.path)
        return p if p.exists() else None
    if cfg.revision is None:
        return None
    hub = Path(os.environ.get("HF_HOME", Path.home() / ".cache" / "huggingface"))
    snap = hub / "hub" / f"models--{cfg.source.replace('/', '--')}" / "snapshots" / cfg.revision
    return snap if snap.exists() else None


def weights_gb(d: Path | None) -> float | None:
    if d is None:
        return None
    files = [*d.glob("*.safetensors"), *d.glob("*.gguf")]
    return sum(f.resolve().stat().st_size for f in files) / 1e9 if files else None


def _latest(pattern: str, root: Path) -> dict[str, Any] | None:
    hits = sorted(root.glob(pattern))
    return io.read_json(hits[-1]) if hits else None


def collect(runs: Path = PROJECT_ROOT / "runs") -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for rid in RUNGS:
        cfg = load(CONFIG_ROOT / "models" / f"{rid}.yaml", cls=ModelCfg)
        q = (
            load(CONFIG_ROOT / "quant" / f"{cfg.quant_format}.yaml", cls=QuantCfg)
            if cfg.quant_format
            else None
        )
        recipe_f = Path(cfg.path) / "recipe.json" if cfg.source_type == "local" else None
        recipe = io.read_json(recipe_f) if recipe_f and recipe_f.exists() else None
        bench = _latest(f"teacher_bench/{rid}_n*/summary.json", runs)
        ev = _latest(f"eval/{rid}__math500__n1__*/summary.json", runs)
        m500 = ev["suites"]["math500"] if ev else None
        out[rid] = {
            "format": q.scheme if q else "BF16",
            "backend": cfg.backend.value,
            "tool": (recipe or {}).get("tool") or (q.tool if q else None),
            "tool_version": (recipe or {}).get("tool_version"),
            "calibration_sha256": (recipe or {}).get("calibration_sha256"),
            "memory_gb": weights_gb(weights_dir(cfg)),  # weights on disk (decimal GB)
            "load_s": bench["load_s"] if bench else None,
            "load_delta_gb": bench["load_delta_gb"] if bench else None,
            "kv_cache_gb": bench["kv_cache_gb"] if bench else None,
            "scored_tokens_per_s": bench["scored_tokens_per_s"] if bench else None,
            "math500": m500["pass_at_1"] if m500 and m500.get("complete") else None,
        }
    return out


def _c(v: Any, fmt: str) -> str:
    return "TBD" if v is None else fmt.format(v)


def write(
    results: dict[str, dict[str, Any]], report: Path = REPORT, json_path: Path = RESULTS
) -> Path:
    io.write_json(json_path, results)
    lines = [
        "# Teacher rungs (steps 4.1–4.4)",
        "",
        "Generated by `qopd report rungs` from `runs/teacher_bench/`, `runs/eval/`, "
        "`models/quant/<rung>/recipe.json` and the weight files; do not edit by hand.",
        "",
        "| Rung | Format | Backend | Tool (version) | Weights (GB) | Load (s) | Load Δmem (GB) "
        "| Scoring tok/s | MATH-500 |",
        "| --- | --- | --- | --- | ---: | ---: | ---: | ---: | ---: |",
    ]
    for rid, r in results.items():
        if r["format"] == "BF16":
            tool = "—"  # not quantized
        elif r["tool"] is None:
            tool = "TBD"  # tool chosen in 4.2 (e.g. NVFP4: ModelOpt or llm-compressor)
        else:
            tool = f"{r['tool']} ({r['tool_version'] or 'TBD'})"
        lines.append(
            f"| {rid} | {r['format']} | {r['backend']} | {tool} | {_c(r['memory_gb'], '{:.1f}')} | "
            f"{_c(r['load_s'], '{:.0f}')} | {_c(r['load_delta_gb'], '{:.1f}')} | "
            f"{_c(r['scored_tokens_per_s'], '{:,.0f}')} | {_c(r['math500'], '{:.1%}')} |"
        )
    kv = sorted({str(r["kv_cache_gb"]) for r in results.values() if r["kv_cache_gb"]})
    lines += [
        "",
        f"Load Δmem includes the engine's KV cache ({', '.join(kv) or 'TBD'} GB). "
        "Scoring: 200 sequences of up to 4,096 response tokens, top-20 log-probs.",
        "",
    ]
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines))
    return report
