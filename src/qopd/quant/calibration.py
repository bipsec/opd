"""Calibration texts for every quantized rung (PLAN 4.1).

Doc: the 512 calibration prompts, each paired with a BF16-teacher reasoning trace in chat format,
cut at 2,048 tokens; every rung in 4.2 uses these same texts. Each trace is generated by T16 in
thinking mode with the evaluation sampling settings (temperature 0.6, top-p 0.95; the doc does
not specify them) and a per-request ``max_tokens = 2048 - len(prompt)``, so each prompt + trace
runs to 2,048 tokens unless the teacher stops earlier.

Output: ``data/calibration/t16_traces.jsonl`` (exact ids + the decoded chat text) and
``data/calibration/calibration_stats.json`` (counts, lengths, sha256).
"""

from __future__ import annotations

import statistics
from pathlib import Path
from typing import Any

from qopd.config import PROJECT_ROOT, project_relative
from qopd.utils import io
from qopd.utils.logging import get_logger

log = get_logger("quant.calibration")
CALIB_DIR = PROJECT_ROOT / "data" / "calibration"


def make_records(
    problems: list[Any], rollouts: list[Any], tok: Any, max_total: int
) -> list[dict[str, Any]]:
    by_id = {p.id: p for p in problems}
    out = []
    for r in rollouts:
        ids = r.input_ids[:max_total]
        out.append(
            {
                "id": r.problem_id,
                "source": by_id[r.problem_id].source,
                "prompt_ids": r.prompt_ids,
                "response_ids": ids[len(r.prompt_ids) :],
                "finish_reason": r.finish_reason.value,
                "text": tok.decode(
                    ids, skip_special_tokens=False
                ),  # chat format, as a quantizer reads it
            }
        )
    return out


def write_stats(records: list[dict[str, Any]], path: Path, max_total: int) -> dict[str, Any]:
    lens = [len(r["prompt_ids"]) + len(r["response_ids"]) for r in records]
    stats = {
        "step": "4.1",
        "file": project_relative(path),
        "sha256": io.sha256_file(path),
        "n": len(records),
        "max_total_tokens": max_total,
        "total_tokens_mean": statistics.fmean(lens),
        "total_tokens_min": min(lens),
        "total_tokens_max": max(lens),
        "reached_limit": sum(1 for x in lens if x >= max_total),
    }
    io.write_json(path.with_name("calibration_stats.json"), stats)
    return stats


def generate_traces(
    teacher_id: str = "T16",
    max_total: int = 2048,
    kv_cache_gb: float = 16.0,
    gpu_memory_utilization: float = 0.75,
    seed: int = 0,
) -> dict[str, Any]:
    """Generate (or reuse) the calibration traces; returns the stats."""
    from qopd.config import CONFIG_ROOT, EvalCfg, load  # noqa: PLC0415
    from qopd.data.sources import read_parquet  # noqa: PLC0415
    from qopd.models.loading import load_tokenizer  # noqa: PLC0415
    from qopd.models.registry import resolve  # noqa: PLC0415
    from qopd.prompts.templates import prompt_ids  # noqa: PLC0415
    from qopd.rollout.engine import RolloutEngine  # noqa: PLC0415
    from qopd.train.opd_loop import request_seed  # noqa: PLC0415

    out = CALIB_DIR / f"{teacher_id.lower()}_traces.jsonl"
    if out.exists():
        return io.read_json(out.with_name("calibration_stats.json"))
    cfg = resolve(teacher_id)
    tok = load_tokenizer(cfg)
    problems = read_parquet(PROJECT_ROOT / "data" / "splits" / "calibration.parquet")
    prompts = [prompt_ids(tok, p) for p in problems]
    # per-request budget: each prompt + trace runs to max_total unless the teacher stops earlier
    budgets = [max_total - len(p) for p in prompts]
    if min(budgets) <= 0:
        raise ValueError("a calibration prompt is longer than the 2,048-token limit")
    sampling = load(CONFIG_ROOT / "eval" / "default.yaml", cls=EvalCfg).sampling.model_copy(
        update={"max_tokens": max(budgets)}
    )
    engine = RolloutEngine(
        cfg.path,
        cfg.revision,
        kv_cache_gb=kv_cache_gb,
        gpu_memory_utilization=gpu_memory_utilization,
        max_model_len=max_total + 16,
        seed=seed,
        enable_prefix_caching=True,
    )
    engine.start()
    try:
        rollouts, stats = engine.generate(
            prompts,
            sampling,
            n=1,
            problem_ids=[p.id for p in problems],
            seeds=[request_seed(seed, -2, p.id) for p in problems],
            max_tokens=budgets,
        )
    finally:
        engine.stop()
    recs = make_records(problems, rollouts, tok, max_total)
    io.write_jsonl(out, recs)
    st = write_stats(recs, out, max_total)
    st.update(
        generate_s=stats.seconds,
        tokens_per_s=stats.tokens_per_s,
        peak_mem_used_gb=stats.peak_mem_gb,
    )
    io.write_json(out.with_name("calibration_stats.json"), st)
    return st
