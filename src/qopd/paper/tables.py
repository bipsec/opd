def number_macros() -> dict[str, str]:
    """Macro name -> LaTeX value, for numbers quoted in the prose."""
    pool = _json(PROJECT_ROOT / "data" / "pool" / "pool_stats.json")
    decon = _json(PROJECT_ROOT / "data" / "contamination" / "contamination_stats.json")
    man = _json(PROJECT_ROOT / "data" / "manifest.json")
    agree = _json(PROJECT_ROOT / "runs" / "agreement" / "S2_vllm_vs_hf_s0" / "summary.json")
    opd = load(CONFIG_ROOT / "train" / "opd.yaml", cls=OPDCfg)
    m: dict[str, str] = {
        "nPoolRaw": num(pool["source"]["rows"]) if pool else TBD,
        "nPoolFiltered": num(pool["pool"]["n"]) if pool else TBD,
        "nPoolClean": num(decon["pool_out"]) if decon else TBD,
        "nDecontDropped": num(decon["dropped"]) if decon else TBD,
        "nMathNearCopy": num(decon["per_suite"]["math500"]["near_copy_eval_items"])
        if decon
        else TBD,
        "nTrain": num(man["splits"]["train"]["n"]) if man else TBD,
        "nColdstart": num(man["splits"]["coldstart"]["n"]) if man else TBD,
        "nCalib": num(man["splits"]["calibration"]["n"]) if man else TBD,
        "nProbe": num(man["splits"]["probe"]["n"]) if man else TBD,
        "agreeMeanAbs": num(agree["mean_abs_diff"], "{:.4f}") if agree else TBD,
        "nPrompts": str(opd.prompts_per_round),
        "nRollouts": str(opd.rollouts_per_prompt),
        "nRounds": str(opd.rounds),
        "rolloutMaxTok": num(opd.rollout.max_tokens),
        "teacherTopK": str(opd.teacher_top_k),
        "entropyBuckets": _entropy_buckets(),
    }
    return m


def _entropy_buckets() -> str:
    from itertools import pairwise  # noqa: PLC0415

    from qopd.fidelity.metrics import DEFAULT_ENTROPY_EDGES  # noqa: PLC0415

    parts = [
        f"[{lo:g},{hi:g})" if hi != float("inf") else f"[{lo:g},\\infty)"
        for lo, hi in pairwise(DEFAULT_ENTROPY_EDGES)
    ]
    return "$" + ", ".join(parts) + "$"


def write_all(out: Path = TABLES) -> list[Path]:
    out.mkdir(parents=True, exist_ok=True)
    written = []
    for name, fn in TABLES_ALL.items():
        p = out / f"{name}.tex"
        p.write_text(fn())
        written.append(p)
    macros = "% generated by scripts/make_paper_tables.py; do not edit\n" + "".join(
        f"\\newcommand{{\\{k}}}{{{v}}}\n" for k, v in number_macros().items()
    )
    (out / "numbers.tex").write_text(macros)
    written.append(out / "numbers.tex")
    return written


def count_tbd(paths: Sequence[Path]) -> int:
    return sum(p.read_text().count(r"\TBD{}") for p in paths if p.exists())
