"""LaTeX tables and number macros for ``paper/`` (PLAN 11.3), generated only from files.

Sources: ``runs/**/summary.json``, ``reports/*.json``, the ``data/**`` stats files that
``reports/data.md`` is rendered from, ``data/manifest.json`` and ``configs/`` (settings,
not results). Anything not available yet is emitted as ``\\TBD{}`` (CLAUDE.md rule 6).

Output: ``paper/tables/*.tex`` (one ``table`` environment each) and
``paper/tables/numbers.tex`` (``\\newcommand`` macros used in the prose).
"""

