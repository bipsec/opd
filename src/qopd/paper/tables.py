def tab_hardware() -> str:
    env = _json(PROJECT_ROOT / "reports" / "env.container.json")
    items = env["items"] if env else {}

    def v(key: str, field: str | None = None) -> str:
        it = items.get(key, {})
        val = it.get("value")
        if val is None:
            return TBD
        return tex(val.get(field) if field and isinstance(val, dict) else val)

    rows = [
        ["GPU", v("gpu (torch)", "name") + ", " + v("gpu (torch)", "capability")],
        ["Memory (unified, GB)", v("unified memory (/proc/meminfo)", "MemTotal_GB")],
        ["CPU", v("cpu", "arch") + ", " + v("cpu", "cpus") + " cores"],
        ["CUDA (container)", v("cuda driver version")],
        ["PyTorch", v("package versions", "torch")],
        ["vLLM", v("package versions", "vllm")],
        ["Transformers", v("package versions", "transformers")],
    ]
    return table(
        "tab:hardware",
        "Hardware and software (one DGX Spark).",
        "ll",
        ["Item", "Value"],
        rows,
        "reports/env.container.json",
    )


def tab_ladder() -> str:
    rows = []
    for mid in LADDER + DENSE:
        m = load(CONFIG_ROOT / "models" / f"{mid}.yaml", cls=ModelCfg)
        if m.quant_format:
            q = load(CONFIG_ROOT / "quant" / f"{m.quant_format}.yaml", cls=QuantCfg)
            fmt, tool = q.scheme, (tex(q.tool) if q.tool else TBD)
            group = str(q.group_size) if q.group_size else "--"
        else:
            fmt, tool, group = "BF16", "--", "--"
        base = "Qwen3-30B-A3B" if mid.startswith("T") else "Qwen3-8B"
        rows.append([tex(mid), base, tex(fmt), f"{m.bits:g}", group, tool, TBD, TBD])
    return table(
        "tab:ladder",
        "Teacher quantization ladder. Memory and MATH-500 accuracy are measured "
        "per rung in Phase 4.",
        "llllllrr",
        ["Rung", "Model", "Format", "Bits", "Group", "Tool", "Memory (GB)", "MATH-500"],
        rows,
        "configs/models, configs/quant",
        note="T2 is an optional stress rung. Memory and accuracy will be read from "
        "\\texttt{reports/rungs.md}.",
    )


def tab_hparams() -> str:
    opd = load(CONFIG_ROOT / "train" / "opd.yaml", cls=OPDCfg)
    sft = load(CONFIG_ROOT / "train" / "sft.yaml", cls=SFTCfg)
    ev = load(CONFIG_ROOT / "eval" / "default.yaml", cls=EvalCfg)
    o, so = opd.optimizer, sft.optimizer
    rows = [
        [
            "Optimizer",
            f"AdamW ($\\beta$={o.betas[0]}, {o.betas[1]}; $\\epsilon$={sci(o.eps)})",
            f"AdamW ($\\beta$={so.betas[0]}, {so.betas[1]}; $\\epsilon$={sci(so.eps)})",
        ],
        [
            "Weight decay / grad clip",
            f"{o.weight_decay:g} / {o.grad_clip_norm:g}",
            f"{so.weight_decay:g} / {so.grad_clip_norm:g}",
        ],
        [
            "Learning rate",
            "sweep 5e-7, 1e-6, 2e-6 (T16), then frozen" if opd.lr is None else sci(opd.lr),
            sci(sft.lr),
        ],
        [
            "Schedule",
            f"linear warmup {opd.warmup_rounds} rounds, constant",
            f"warmup {sft.warmup_ratio:.0%}, cosine to {sft.min_lr_ratio:.0%}".replace("%", r"\%"),
        ],
        [
            "Batch",
            f"{opd.prompts_per_round} prompts $\\times$ {opd.rollouts_per_prompt} rollouts, 1 step",
            f"{sft.global_batch_size} sequences",
        ],
        [
            "Max length",
            f"{opd.rollout.max_tokens:,} response tokens".replace(",", "{,}"),
            f"{sft.max_seq_len:,} tokens (longer dropped)".replace(",", "{,}"),
        ],
        ["Rounds / epochs", f"{opd.rounds} rounds", f"{sft.epochs:g} epoch"],
        ["Rollout sampling", f"T={opd.rollout.temperature:g}, top-p={opd.rollout.top_p:g}", "--"],
        ["Teacher top-k logged", str(opd.teacher_top_k), "--"],
        [
            "Evaluation sampling",
            f"T={ev.sampling.temperature:g}, top-p={ev.sampling.top_p:g}, "
            f"max {num(ev.sampling.max_tokens)} tokens",
            "same",
        ],
    ]
    return table(
        "tab:hparams",
        "Training and evaluation settings, identical for every teacher rung.",
        "lp{5.2cm}p{4.2cm}",
        ["Setting", "OPD", "Cold-start SFT"],
        rows,
        "configs/train/{opd,sft}.yaml, configs/eval/default.yaml",
    )


def tab_data() -> str:
    pool = _json(PROJECT_ROOT / "data" / "pool" / "pool_stats.json")
    decon = _json(PROJECT_ROOT / "data" / "contamination" / "contamination_stats.json")
    man = _json(PROJECT_ROOT / "data" / "manifest.json")
    rows = []
    if pool:
        rows.append(["Raw problems", num(pool["source"]["rows"])])
        for st in pool["stages"]:
            rows.append([tex(f"after {st['stage']}"), num(st["kept"])])
    rows.append(["after 13-gram decontamination", num(decon["pool_out"]) if decon else TBD])
    for name in ("train", "coldstart", "calibration", "probe"):
        n = man["splits"][name]["n"] if man else None
        rows.append([tex(f"split: {name}"), num(n)])
    src = tex(pool["source"]["hf_repo"]) if pool else TBD
    return table(
        "tab:data",
        f"Training data pipeline (source: \\texttt{{{src}}}).",
        "lr",
        ["Stage", "Problems"],
        rows,
        "data/pool/pool_stats.json, data/contamination/contamination_stats.json, "
        "data/manifest.json",
    )


def tab_eval_suites() -> str:
    ev = load(CONFIG_ROOT / "eval" / "default.yaml", cls=EvalCfg)
    stats = _json(PROJECT_ROOT / "data" / "eval" / "eval_stats.json") or {"suites": {}}
    decon = _json(PROJECT_ROOT / "data" / "contamination" / "contamination_stats.json")
    rows = []
    for name, s in ev.suites.items():
        st = stats["suites"].get(name, {})
        n = num(st["n"]) if st.get("status") == "ok" else TBD
        hit = TBD
        if decon and name in decon["per_suite"]:
            hit = num(decon["per_suite"][name]["train_dropped"])
        rows.append(
            [SUITE_LABELS.get(name, tex(name)), n, str(s.n_samples), tex(s.source or TBD), hit]
        )
    return table(
        "tab:evals",
        "Evaluation suites, samples per problem, and training prompts "
        "removed for 13-gram overlap with each suite.",
        "lrrlr",
        ["Benchmark", "Items", "Samples", "Source", "Train dropped"],
        rows,
        "configs/eval/default.yaml, data/eval/eval_stats.json, "
        "data/contamination/contamination_stats.json",
    )


def tab_sanity() -> str:
    from qopd.eval.report import suite_results  # noqa: PLC0415

    expected = {"gsm8k": 1319, "math500": 500}
    rows = []
    for m in ("S2", "S1"):
        res = suite_results(
            PROJECT_ROOT / "runs" / "eval" / f"{m}__gsm8k+math500__n1__t16384__s0", expected
        )
        cells = [m]
        for s in expected:
            r = res.get(s)
            ok = r is not None and r["complete"]
            cells += [pct(r["pass_at_1"]) if ok else TBD, pct(r["truncation_rate"]) if ok else TBD]
        cells += [TBD, TBD]  # published (Qwen3 technical report)
        rows.append(cells)
    return table(
        "tab:sanity",
        "Sanity evaluation of the official students (thinking mode, "
        "1 sample, 16{,}384 tokens): pass@1 and truncation rate (\\%).",
        "lrrrrrr",
        ["Student", "GSM8K", "trunc.", "MATH-500", "trunc.", "Rep. GSM8K", "Rep. MATH-500"],
        rows,
        "runs/eval/S{1,2}__gsm8k+math500__n1__t16384__s0",
        note="Rep.: published Qwen3 technical-report values, TBD until added with a page citation.",
    )


