# --- helpers -------------------------------------------------------------------------------

_ESC = {
    "\\": r"\textbackslash{}",
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "{": r"\{",
    "}": r"\}",
    "~": r"\textasciitilde{}",
    "^": r"\^{}",
}


def tex(s: Any) -> str:
    return "".join(_ESC.get(c, c) for c in str(s))


def num(x: float | int | None, fmt: str = "{:,}") -> str:
    if x is None:
        return TBD
    return fmt.format(x).replace(",", "{,}")


def sci(x: float) -> str:
    """1e-08 -> $10^{-8}$, 1e-05 -> $10^{-5}$, 2e-05 -> $2\\times10^{-5}$."""
    mant, exp = f"{x:.0e}".split("e")
    e = int(exp)
    return f"$10^{{{e}}}$" if mant == "1" else f"${mant}\\times10^{{{e}}}$"


def pct(x: float | None, digits: int = 1) -> str:
    return TBD if x is None else f"{100 * x:.{digits}f}"


def _json(path: Path) -> dict[str, Any] | None:
    return io.read_json(path) if path.exists() else None


def table(
    label: str,
    caption: str,
    cols: str,
    header: Sequence[str],
    rows: Sequence[Sequence[str]],
    source: str,
    note: str = "",
) -> str:
    body = "\n".join("    " + " & ".join(r) + r" \\" for r in rows)
    foot = rf"\par\smallskip\footnotesize{{{note}}}" if note else ""
    return (
        f"% generated by scripts/make_paper_tables.py from {source}; do not edit\n"
        "\\begin{table}[t]\n  \\centering\\small\n"
        f"  \\caption{{{caption}}}\\label{{{label}}}\n"
        f"  \\begin{{tabular}}{{{cols}}}\n    \\toprule\n"
        "    " + " & ".join(header) + " \\\\\n    \\midrule\n"
        f"{body}\n    \\bottomrule\n  \\end{{tabular}}{foot}\n\\end{{table}}\n"
    )


