"""Evaluation reports rendered only from files under runs/ (CLAUDE.md rule 6)."""

from __future__ import annotations

from pathlib import Path
from typing import Any

from qopd.config import PROJECT_ROOT, project_relative
from qopd.eval.runner import summarize_suite
from qopd.utils import io

SANITY_REPORT = PROJECT_ROOT / "reports" / "sanity_eval.md"


def suite_results(run_dir: Path, expected: dict[str, int]) -> dict[str, dict[str, Any] | None]:
    """Per-suite summary from summary.json, or computed from samples.jsonl while running."""
    summary = run_dir / "summary.json"
    if summary.exists():
        return {s: io.read_json(summary)["suites"].get(s) for s in expected}
    samples = run_dir / "samples.jsonl"
    rows = io.read_jsonl(samples) if samples.exists() else []
    state = io.read_json(run_dir / "state.json") if (run_dir / "state.json").exists() else {}
    out: dict[str, dict[str, Any] | None] = {}
    for suite, n in expected.items():
        r = [x for x in rows if x["suite"] == suite]
        out[suite] = (
            summarize_suite(r, n, 1, state.get("gen_seconds", {}).get(suite, 0.0)) if r else None
        )
    return out


def _fmt_time(seconds: float) -> str:
    m = round(seconds / 60)
    return f"{m // 60} h {m % 60:02d} min" if m >= 60 else f"{m} min"


def write_sanity_report(
    runs: dict[str, Path],
    expected: dict[str, int],
    published: dict[tuple[str, str], str] | None = None,
    report: Path = SANITY_REPORT,
) -> Path:
    """``runs``: model id -> run dir. ``published``: (model, suite) -> value with citation."""
    published = published or {}
    lines = [
        "# Sanity evaluation (step 3.3)",
        "",
        "Official post-trained students, thinking mode, temperature 0.6, top-p 0.95, max 16,384 "
        "tokens, 1 sample per problem. Generated by `scripts/sanity_report.py` from the run "
        "directories below; values marked TBD are not available yet.",
        "",
        "| Model | Suite | pass@1 | ± s.e. | Done | Mean tokens | Truncated | No answer | "
        "Generation time | tok/s | Qwen3 report |",
        "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |",
    ]
    for model, run_dir in runs.items():
        res = suite_results(run_dir, expected)
        for suite, n in expected.items():
            r = res.get(suite)
            pub = published.get((model, suite), "TBD")
            if r is None:
                tbd5 = " | ".join(["TBD"] * 5)
                lines.append(f"| {model} | {suite} | TBD | TBD | 0/{n} | {tbd5} | {pub} |")
                continue
            done = f"{r['n_samples_done']}/{n}"
            if r["complete"]:
                cells = [
                    f"{100 * r['pass_at_1']:.1f}",
                    f"{100 * r['stderr_over_problems']:.1f}",
                    done,
                    f"{r['mean_response_tokens']:.0f}",
                    f"{100 * r['truncation_rate']:.1f}%",
                    f"{100 * r['no_answer_rate']:.1f}%",
                    _fmt_time(r["gen_seconds"]),
                    f"{r['tokens_per_s']:.0f}",
                ]
                lines.append(f"| {model} | {suite} | {' | '.join(cells)} | {pub} |")
            else:
                lines.append(
                    f"| {model} | {suite} | TBD (running) | TBD | {done} | TBD | TBD | TBD "
                    f"| TBD | TBD | {pub} |"
                )
    lines += ["", "Sources:", ""]
    lines += [f"- {m}: `{project_relative(d)}/`" for m, d in runs.items()]
    lines += [
        "",
        "Qwen3 report: arXiv:2505.09388 (`reports/published/qwen3_tech_report.json`); its "
        "thinking-mode decoding is top-k 20 and up to 32,768 output tokens, ours top-k off and "
        "16,384 (doc setting).",
        "",
    ]
    lines += [
        "",
        "pass@1 and its standard error are in percentage points; truncated = hit 16,384 tokens; "
        "no answer = no final answer after `</think>` or nothing parsable. Generation time is "
        "wall-clock inside `generate` (engine load excluded), summed over resumes.",
        "",
    ]
    report.parent.mkdir(parents=True, exist_ok=True)
    report.write_text("\n".join(lines))
    return report
